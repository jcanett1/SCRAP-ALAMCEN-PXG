-- Tabla de requisiciones de material para Supabase/PostgreSQL.
-- Los números de parte y descripciones se administran en el frontend.
-- Ejecuta este archivo completo en Supabase > SQL Editor.

create table if not exists public.requisiciones_material (
  id bigint generated by default as identity primary key,
  fecha date not null default current_date,
  material_part_number text not null,
  material_description text not null,
  cantidad integer not null check (cantidad > 0),
  motivo text not null check (char_length(trim(motivo)) > 0),
  quien_pide text not null check (
    quien_pide in (
      'CELDA 11',
      'CELDA 10',
      'CELDA 16',
      'CELDA 15',
      'PREP AREA',
      'TECNICOS',
      'INGENIERIA'
    )
  ),
  entrego text not null,
  revisado boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Compatibilidad con la tabla existente: las requisiciones actuales comienzan pendientes.
alter table public.requisiciones_material
  add column if not exists revisado boolean not null default false;

comment on column public.requisiciones_material.revisado is
  'Indica si la requisición ya fue revisada o capturada';

-- Actualiza el catálogo admitido tanto en instalaciones nuevas como existentes.
alter table public.requisiciones_material
  drop constraint if exists requisiciones_material_entrego_check;

alter table public.requisiciones_material
  add constraint requisiciones_material_entrego_check
  check (
    entrego in (
      'DENISSE SANZARRIC',
      'YODELI LOPEZ',
      'DIANA MENDEZ',
      'YAJAIRA ONTIVEROS',
      'MAREDNA PUIG'
    )
  );

create index if not exists requisiciones_material_fecha_idx
  on public.requisiciones_material (fecha desc);

create index if not exists requisiciones_material_part_number_idx
  on public.requisiciones_material (material_part_number);

comment on table public.requisiciones_material is
  'Requisiciones de material; el catálogo de materiales se administra en el frontend';

-- Seguridad para la aplicación pública: consulta y captura como antes.
alter table public.requisiciones_material enable row level security;

drop policy if exists requisiciones_material_select on public.requisiciones_material;
create policy requisiciones_material_select
  on public.requisiciones_material
  for select
  to anon, authenticated
  using (true);

drop policy if exists requisiciones_material_insert on public.requisiciones_material;
create policy requisiciones_material_insert
  on public.requisiciones_material
  for insert
  to anon, authenticated
  with check (true);

-- La app escribe por RPC para exigir motivo, auditoría y bloqueo de revisadas.
revoke update, delete on table public.requisiciones_material from public, anon, authenticated;

-- Auditoría privada: conserva el motivo obligatorio y la instantánea anterior/después.
create table if not exists public.requisiciones_material_auditoria (
  id bigint generated by default as identity primary key,
  requisicion_id bigint not null,
  accion text not null check (accion in ('EDICION', 'ELIMINACION')),
  motivo_cambio text not null check (char_length(trim(motivo_cambio)) > 0),
  datos_anteriores jsonb not null,
  datos_nuevos jsonb,
  creado_en timestamptz not null default now()
);

create index if not exists requisiciones_material_auditoria_requisicion_idx
  on public.requisiciones_material_auditoria (requisicion_id, creado_en desc);

comment on table public.requisiciones_material_auditoria is
  'Historial privado de cambios y eliminaciones de requisiciones con motivo obligatorio';

alter table public.requisiciones_material_auditoria enable row level security;
revoke all on table public.requisiciones_material_auditoria from public, anon, authenticated;

-- Las operaciones de cambio pasan por estas funciones transaccionales; no se abren
-- políticas UPDATE/DELETE directas en la tabla de requisiciones.
create or replace function public.actualizar_requisicion_material(
  p_id bigint,
  p_fecha date,
  p_material_part_number text,
  p_material_description text,
  p_cantidad integer,
  p_motivo text,
  p_quien_pide text,
  p_entrego text,
  p_motivo_cambio text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_antes public.requisiciones_material%rowtype;
  v_despues public.requisiciones_material%rowtype;
begin
  if p_motivo_cambio is null or pg_catalog.char_length(pg_catalog.btrim(p_motivo_cambio)) = 0 then
    raise exception 'Debes indicar el motivo de la edición.' using errcode = '22023';
  end if;

  select *
    into v_antes
    from public.requisiciones_material as r
   where r.id = p_id
   for update;

  if not found then
    raise exception 'No se encontró la requisición %.', p_id using errcode = 'P0002';
  end if;

  if v_antes.revisado then
    raise exception 'Desmarca la requisición como revisada antes de editarla.' using errcode = '55000';
  end if;

  update public.requisiciones_material as r
     set fecha = p_fecha,
         material_part_number = p_material_part_number,
         material_description = p_material_description,
         cantidad = p_cantidad,
         motivo = p_motivo,
         quien_pide = p_quien_pide,
         entrego = p_entrego,
         updated_at = pg_catalog.now()
   where r.id = p_id
  returning r.* into v_despues;

  insert into public.requisiciones_material_auditoria (
    requisicion_id,
    accion,
    motivo_cambio,
    datos_anteriores,
    datos_nuevos
  ) values (
    p_id,
    'EDICION',
    pg_catalog.btrim(p_motivo_cambio),
    pg_catalog.to_jsonb(v_antes),
    pg_catalog.to_jsonb(v_despues)
  );

  return pg_catalog.to_jsonb(v_despues);
end;
$function$;

create or replace function public.eliminar_requisicion_material(
  p_id bigint,
  p_motivo_cambio text
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_antes public.requisiciones_material%rowtype;
begin
  if p_motivo_cambio is null or pg_catalog.char_length(pg_catalog.btrim(p_motivo_cambio)) = 0 then
    raise exception 'Debes indicar el motivo de la eliminación.' using errcode = '22023';
  end if;

  select *
    into v_antes
    from public.requisiciones_material as r
   where r.id = p_id
   for update;

  if not found then
    raise exception 'No se encontró la requisición %.', p_id using errcode = 'P0002';
  end if;

  if v_antes.revisado then
    raise exception 'Desmarca la requisición como revisada antes de eliminarla.' using errcode = '55000';
  end if;

  insert into public.requisiciones_material_auditoria (
    requisicion_id,
    accion,
    motivo_cambio,
    datos_anteriores,
    datos_nuevos
  ) values (
    p_id,
    'ELIMINACION',
    pg_catalog.btrim(p_motivo_cambio),
    pg_catalog.to_jsonb(v_antes),
    null
  );

  delete from public.requisiciones_material as r where r.id = p_id;

  return pg_catalog.jsonb_build_object('success', true, 'id', p_id);
end;
$function$;

revoke all on function public.actualizar_requisicion_material(bigint, date, text, text, integer, text, text, text, text) from public;
revoke all on function public.eliminar_requisicion_material(bigint, text) from public;
grant execute on function public.actualizar_requisicion_material(bigint, date, text, text, integer, text, text, text, text) to anon, authenticated;
grant execute on function public.eliminar_requisicion_material(bigint, text) to anon, authenticated;


create or replace function public.marcar_requisicion_material_revisado(
  p_id bigint,
  p_revisado boolean
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $function$
declare
  v_despues public.requisiciones_material%rowtype;
begin
  if p_revisado is null then
    raise exception 'Debes indicar si la requisición está revisada.' using errcode = '22023';
  end if;

  update public.requisiciones_material as r
     set revisado = p_revisado,
         updated_at = pg_catalog.now()
   where r.id = p_id
  returning r.* into v_despues;

  if not found then
    raise exception 'No se encontró la requisición %.', p_id using errcode = 'P0002';
  end if;

  return pg_catalog.to_jsonb(v_despues);
end;
$function$;

revoke all on function public.marcar_requisicion_material_revisado(bigint, boolean) from public;
grant execute on function public.marcar_requisicion_material_revisado(bigint, boolean) to anon, authenticated;
